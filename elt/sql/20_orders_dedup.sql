CREATE TABLE IF NOT EXISTS FRESHCART.SILVER.ORDERS_DEDUP (
  ORDER_ID STRING,
  EMAIL STRING,
  CUSTOMER_NAME STRING,
  ORDER_DATE DATE,
  AMOUNT NUMBER(18,2),
  CURRENCY STRING,
  PINCODE STRING,
  UPDATED_AT TIMESTAMP_NTZ,
  SOURCE STRING,
  RUN_ID STRING,
  EXTRACTED_AT TIMESTAMP_TZ,
  INGEST_SEQ NUMBER,
  SRC_FILE STRING,
  SRC_ROW NUMBER,
  RAW VARIANT
);

MERGE INTO FRESHCART.SILVER.ORDERS_DEDUP AS target
USING (
  SELECT
    ORDER_ID,
    EMAIL,
    CUSTOMER_NAME,
    ORDER_DATE,
    AMOUNT,
    CURRENCY,
    PINCODE,
    UPDATED_AT,
    SOURCE,
    RUN_ID,
    EXTRACTED_AT,
    INGEST_SEQ,
    SRC_FILE,
    SRC_ROW,
    RAW
  FROM FRESHCART.SILVER.ORDERS_CLEAN
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ORDER_ID
    ORDER BY
      UPDATED_AT DESC NULLS LAST,
      IFF(LOWER(SOURCE) = 'mobile', 1, 0) DESC,
      RUN_ID DESC,
      SRC_FILE DESC,
      SRC_ROW DESC,
      INGEST_SEQ DESC
  ) = 1
) AS source
ON target.ORDER_ID = source.ORDER_ID
WHEN MATCHED THEN UPDATE SET
  EMAIL = source.EMAIL,
  CUSTOMER_NAME = source.CUSTOMER_NAME,
  ORDER_DATE = source.ORDER_DATE,
  AMOUNT = source.AMOUNT,
  CURRENCY = source.CURRENCY,
  PINCODE = source.PINCODE,
  UPDATED_AT = source.UPDATED_AT,
  SOURCE = source.SOURCE,
  RUN_ID = source.RUN_ID,
  EXTRACTED_AT = source.EXTRACTED_AT,
  INGEST_SEQ = source.INGEST_SEQ,
  SRC_FILE = source.SRC_FILE,
  SRC_ROW = source.SRC_ROW,
  RAW = source.RAW
WHEN NOT MATCHED THEN INSERT (
  ORDER_ID,
  EMAIL,
  CUSTOMER_NAME,
  ORDER_DATE,
  AMOUNT,
  CURRENCY,
  PINCODE,
  UPDATED_AT,
  SOURCE,
  RUN_ID,
  EXTRACTED_AT,
  INGEST_SEQ,
  SRC_FILE,
  SRC_ROW,
  RAW
) VALUES (
  source.ORDER_ID,
  source.EMAIL,
  source.CUSTOMER_NAME,
  source.ORDER_DATE,
  source.AMOUNT,
  source.CURRENCY,
  source.PINCODE,
  source.UPDATED_AT,
  source.SOURCE,
  source.RUN_ID,
  source.EXTRACTED_AT,
  source.INGEST_SEQ,
  source.SRC_FILE,
  source.SRC_ROW,
  source.RAW
);