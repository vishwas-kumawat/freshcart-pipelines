CREATE TABLE IF NOT EXISTS FRESHCART.SILVER.ORDERS_CHECKED (
  ORDER_ID STRING,
  EMAIL STRING,
  CUSTOMER_NAME STRING,
  ORDER_DATE DATE,
  AMOUNT NUMBER(18,2),
  CURRENCY STRING,
  PINCODE STRING,
  UPDATED_AT TIMESTAMP_NTZ,
  SOURCE STRING,
  RUN_ID STRING,
  EXTRACTED_AT TIMESTAMP_TZ,
  INGEST_SEQ NUMBER,
  SRC_FILE STRING,
  SRC_ROW NUMBER,
  RAW VARIANT,
  VALIDATION_REASONS ARRAY,
  IS_VALID BOOLEAN
);

MERGE INTO FRESHCART.SILVER.ORDERS_CHECKED AS target
USING (
  WITH raw_orders AS (
    SELECT
      br.SOURCE,
      br.RUN_ID,
      br.EXTRACTED_AT,
      br.INGEST_SEQ,
      br.SRC_FILE,
      br.SRC_ROW,
      br.RAW,
      COALESCE(br.RAW:order_id::STRING, br.RAW:orderId::STRING) AS ORDER_ID,
      COALESCE(
        br.RAW:cust_email::STRING,
        br.RAW:customer:email::STRING
      ) AS EMAIL_VALUE,
      COALESCE(
        br.RAW:cust_name::STRING,
        br.RAW:customer:name::STRING
      ) AS CUSTOMER_NAME_VALUE,
      COALESCE(
        br.RAW:order_date::STRING,
        br.RAW:orderDate::STRING
      ) AS ORDER_DATE_VALUE,
      COALESCE(
        br.RAW:amount::STRING,
        br.RAW:total:value::STRING
      ) AS AMOUNT_VALUE,
      COALESCE(
        br.RAW:currency::STRING,
        br.RAW:total:currency::STRING
      ) AS CURRENCY_VALUE,
      COALESCE(
        br.RAW:pincode::STRING,
        br.RAW:deliveryPin::STRING
      ) AS PINCODE_VALUE,
      COALESCE(
        br.RAW:updated_at::STRING,
        br.RAW:updatedAt::STRING
      ) AS UPDATED_AT_VALUE
    FROM FRESHCART.BRONZE.ORDERS_RAW AS br
  ),
  normalized AS (
    SELECT
      ORDER_ID,
      LOWER(TRIM(EMAIL_VALUE)) AS EMAIL,
      INITCAP(REGEXP_REPLACE(TRIM(CUSTOMER_NAME_VALUE), '[[:space:]]+', ' '))
        AS CUSTOMER_NAME,
      COALESCE(
        TRY_TO_DATE(ORDER_DATE_VALUE, 'YYYY-MM-DD'),
        TRY_TO_DATE(ORDER_DATE_VALUE, 'DD/MM/YYYY'),
        TRY_TO_DATE(ORDER_DATE_VALUE, 'MON DD, YYYY')
      ) AS ORDER_DATE,
      CASE
        WHEN AMOUNT_VALUE IS NULL OR TRIM(AMOUNT_VALUE) = '' THEN NULL
        ELSE TRY_TO_DECIMAL(
          REGEXP_REPLACE(AMOUNT_VALUE, '[^0-9.-]', ''),
          18,
          2
        )
      END AS AMOUNT,
      UPPER(TRIM(CURRENCY_VALUE)) AS CURRENCY,
      TRIM(PINCODE_VALUE) AS PINCODE,
      COALESCE(
        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT_VALUE),
        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT_VALUE, 'YYYY-MM-DD HH24:MI:SS'),
        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT_VALUE, 'YYYY-MM-DD"T"HH24:MI:SS')
      ) AS UPDATED_AT,
      SOURCE,
      RUN_ID,
      EXTRACTED_AT,
      INGEST_SEQ,
      SRC_FILE,
      SRC_ROW,
      RAW,
      AMOUNT_VALUE
    FROM raw_orders
  ),
  reasons AS (
    SELECT
      normalized.*,
      ARRAY_CONSTRUCT_COMPACT(
        IFF(ORDER_ID IS NULL OR TRIM(ORDER_ID) = '', 'MISSING_ORDER_ID', NULL),
        IFF(
          EMAIL IS NULL OR NOT REGEXP_LIKE(
            EMAIL,
            '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+[.][A-Za-z]{2,}$'
          ),
          'INVALID_EMAIL',
          NULL
        ),
        IFF(ORDER_DATE IS NULL, 'INVALID_ORDER_DATE', NULL),
        IFF(
          AMOUNT_VALUE IS NOT NULL
            AND TRIM(AMOUNT_VALUE) <> ''
            AND AMOUNT IS NULL,
          'INVALID_AMOUNT',
          NULL
        ),
        IFF(AMOUNT < 0, 'NEGATIVE_AMOUNT', NULL),
        IFF(
          PINCODE IS NULL OR NOT REGEXP_LIKE(PINCODE, '^[0-9]{6}$'),
          'INVALID_PINCODE',
          NULL
        )
      ) AS VALIDATION_REASONS
    FROM normalized
  )
  SELECT
    ORDER_ID,
    EMAIL,
    CUSTOMER_NAME,
    ORDER_DATE,
    AMOUNT,
    CURRENCY,
    PINCODE,
    UPDATED_AT,
    SOURCE,
    RUN_ID,
    EXTRACTED_AT,
    INGEST_SEQ,
    SRC_FILE,
    SRC_ROW,
    RAW,
    VALIDATION_REASONS,
    ARRAY_SIZE(VALIDATION_REASONS) = 0 AS IS_VALID
  FROM reasons
) AS source
ON target.INGEST_SEQ = source.INGEST_SEQ
WHEN MATCHED THEN UPDATE SET
  ORDER_ID = source.ORDER_ID,
  EMAIL = source.EMAIL,
  CUSTOMER_NAME = source.CUSTOMER_NAME,
  ORDER_DATE = source.ORDER_DATE,
  AMOUNT = source.AMOUNT,
  CURRENCY = source.CURRENCY,
  PINCODE = source.PINCODE,
  UPDATED_AT = source.UPDATED_AT,
  SOURCE = source.SOURCE,
  RUN_ID = source.RUN_ID,
  EXTRACTED_AT = source.EXTRACTED_AT,
  SRC_FILE = source.SRC_FILE,
  SRC_ROW = source.SRC_ROW,
  RAW = source.RAW,
  VALIDATION_REASONS = source.VALIDATION_REASONS,
  IS_VALID = source.IS_VALID
WHEN NOT MATCHED THEN INSERT (
  ORDER_ID,
  EMAIL,
  CUSTOMER_NAME,
  ORDER_DATE,
  AMOUNT,
  CURRENCY,
  PINCODE,
  UPDATED_AT,
  SOURCE,
  RUN_ID,
  EXTRACTED_AT,
  INGEST_SEQ,
  SRC_FILE,
  SRC_ROW,
  RAW,
  VALIDATION_REASONS,
  IS_VALID
) VALUES (
  source.ORDER_ID,
  source.EMAIL,
  source.CUSTOMER_NAME,
  source.ORDER_DATE,
  source.AMOUNT,
  source.CURRENCY,
  source.PINCODE,
  source.UPDATED_AT,
  source.SOURCE,
  source.RUN_ID,
  source.EXTRACTED_AT,
  source.INGEST_SEQ,
  source.SRC_FILE,
  source.SRC_ROW,
  source.RAW,
  source.VALIDATION_REASONS,
  source.IS_VALID
);

CREATE TABLE IF NOT EXISTS FRESHCART.SILVER.ORDERS_CLEAN (
  ORDER_ID STRING,
  EMAIL STRING,
  CUSTOMER_NAME STRING,
  ORDER_DATE DATE,
  AMOUNT NUMBER(18,2),
  CURRENCY STRING,
  PINCODE STRING,
  UPDATED_AT TIMESTAMP_NTZ,
  SOURCE STRING,
  RUN_ID STRING,
  EXTRACTED_AT TIMESTAMP_TZ,
  INGEST_SEQ NUMBER,
  SRC_FILE STRING,
  SRC_ROW NUMBER,
  RAW VARIANT,
  VALIDATION_REASONS ARRAY,
  IS_VALID BOOLEAN
);

MERGE INTO FRESHCART.SILVER.ORDERS_CLEAN AS target
USING FRESHCART.SILVER.ORDERS_CHECKED AS source
ON target.INGEST_SEQ = source.INGEST_SEQ
WHEN MATCHED AND NOT source.IS_VALID THEN DELETE
WHEN MATCHED AND source.IS_VALID THEN UPDATE SET
  ORDER_ID = source.ORDER_ID,
  EMAIL = source.EMAIL,
  CUSTOMER_NAME = source.CUSTOMER_NAME,
  ORDER_DATE = source.ORDER_DATE,
  AMOUNT = source.AMOUNT,
  CURRENCY = source.CURRENCY,
  PINCODE = source.PINCODE,
  UPDATED_AT = source.UPDATED_AT,
  SOURCE = source.SOURCE,
  RUN_ID = source.RUN_ID,
  EXTRACTED_AT = source.EXTRACTED_AT,
  SRC_FILE = source.SRC_FILE,
  SRC_ROW = source.SRC_ROW,
  RAW = source.RAW,
  VALIDATION_REASONS = source.VALIDATION_REASONS,
  IS_VALID = source.IS_VALID
WHEN NOT MATCHED AND source.IS_VALID THEN INSERT (
  ORDER_ID,
  EMAIL,
  CUSTOMER_NAME,
  ORDER_DATE,
  AMOUNT,
  CURRENCY,
  PINCODE,
  UPDATED_AT,
  SOURCE,
  RUN_ID,
  EXTRACTED_AT,
  INGEST_SEQ,
  SRC_FILE,
  SRC_ROW,
  RAW,
  VALIDATION_REASONS,
  IS_VALID
) VALUES (
  source.ORDER_ID,
  source.EMAIL,
  source.CUSTOMER_NAME,
  source.ORDER_DATE,
  source.AMOUNT,
  source.CURRENCY,
  source.PINCODE,
  source.UPDATED_AT,
  source.SOURCE,
  source.RUN_ID,
  source.EXTRACTED_AT,
  source.INGEST_SEQ,
  source.SRC_FILE,
  source.SRC_ROW,
  source.RAW,
  source.VALIDATION_REASONS,
  source.IS_VALID
);

MERGE INTO FRESHCART.QUARANTINE.ORDERS AS target
USING (
  SELECT
    RUN_ID,
    SOURCE,
    ORDER_ID,
    INGEST_SEQ,
    VALIDATION_REASONS,
    RAW
  FROM FRESHCART.SILVER.ORDERS_CHECKED
  WHERE NOT IS_VALID
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RUN_ID, ORDER_ID
    ORDER BY INGEST_SEQ DESC
  ) = 1
) AS source
ON target.RUN_ID = source.RUN_ID
  AND target.ORDER_ID = source.ORDER_ID
WHEN MATCHED THEN UPDATE SET
  INGEST_SEQ = source.INGEST_SEQ,
  SOURCE = source.SOURCE,
  REASONS = source.VALIDATION_REASONS,
  ROW_DATA = source.RAW
WHEN NOT MATCHED THEN INSERT (
  RUN_ID,
  INGEST_SEQ,
  SOURCE,
  ORDER_ID,
  REASONS,
  ROW_DATA
) VALUES (
  source.RUN_ID,
  source.INGEST_SEQ,
  source.SOURCE,
  source.ORDER_ID,
  source.VALIDATION_REASONS,
  source.RAW
);