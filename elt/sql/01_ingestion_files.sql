-- Additive standard-table ledger for trial-account compatibility.
-- Standard Snowflake table constraints do not enforce FILE_ID uniqueness.
CREATE TABLE IF NOT EXISTS FRESHCART.OPS.INGESTION_FILES (
  FILE_ID VARCHAR(64) NOT NULL,
  SOURCE VARCHAR(32) NOT NULL,
  RUN_ID VARCHAR(256) NOT NULL,
  FILE_PATH VARCHAR NOT NULL,
  STAGE_PATH VARCHAR NOT NULL,
  CONTENT_SHA256 VARCHAR(64) NOT NULL,
  EXPECTED_ROWS NUMBER NOT NULL,
  STATUS VARCHAR(16) NOT NULL,
  LOADED_ROWS NUMBER NOT NULL,
  COPY_QUERY_ID VARCHAR(100),
  LAST_ERROR VARCHAR(2000),
  CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);