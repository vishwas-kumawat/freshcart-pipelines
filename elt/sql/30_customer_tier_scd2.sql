CREATE TABLE IF NOT EXISTS FRESHCART.DIM.CUSTOMERS_SCD2 (
  CUST_ID STRING,
  EMAIL STRING,
  TIER STRING,
  EFFECTIVE_FROM DATE,
  EFFECTIVE_TO DATE,
  IS_CURRENT BOOLEAN,
  SOURCE STRING,
  RUN_ID STRING,
  INGEST_SEQ NUMBER
);

MERGE INTO FRESHCART.DIM.CUSTOMERS_SCD2 AS target
USING (
  WITH source_events AS (
    SELECT
      RAW:cust_id::STRING AS CUST_ID,
      LOWER(TRIM(RAW:email::STRING)) AS EMAIL,
      INITCAP(TRIM(RAW:tier::STRING)) AS TIER,
      TRY_TO_DATE(RAW:effective_from::STRING) AS EFFECTIVE_FROM,
      SOURCE,
      RUN_ID,
      INGEST_SEQ
    FROM FRESHCART.BRONZE.CUSTOMERS_RAW
    WHERE RAW:cust_id IS NOT NULL
      AND RAW:effective_from IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY
        RAW:cust_id::STRING,
        TRY_TO_DATE(RAW:effective_from::STRING)
      ORDER BY INGEST_SEQ DESC
    ) = 1
  ),
  versioned AS (
    SELECT
      CUST_ID,
      EMAIL,
      TIER,
      EFFECTIVE_FROM,
      DATEADD(
        day,
        -1,
        LEAD(EFFECTIVE_FROM) OVER (
          PARTITION BY CUST_ID ORDER BY EFFECTIVE_FROM
        )
      ) AS EFFECTIVE_TO,
      LEAD(EFFECTIVE_FROM) OVER (
        PARTITION BY CUST_ID ORDER BY EFFECTIVE_FROM
      ) IS NULL AS IS_CURRENT,
      SOURCE,
      RUN_ID,
      INGEST_SEQ
    FROM source_events
    WHERE EFFECTIVE_FROM IS NOT NULL
  )
  SELECT *
  FROM versioned
) AS source
ON target.CUST_ID = source.CUST_ID
  AND target.EFFECTIVE_FROM = source.EFFECTIVE_FROM
WHEN MATCHED THEN UPDATE SET
  EMAIL = source.EMAIL,
  TIER = source.TIER,
  EFFECTIVE_TO = source.EFFECTIVE_TO,
  IS_CURRENT = source.IS_CURRENT,
  SOURCE = source.SOURCE,
  RUN_ID = source.RUN_ID,
  INGEST_SEQ = source.INGEST_SEQ
WHEN NOT MATCHED THEN INSERT (
  CUST_ID,
  EMAIL,
  TIER,
  EFFECTIVE_FROM,
  EFFECTIVE_TO,
  IS_CURRENT,
  SOURCE,
  RUN_ID,
  INGEST_SEQ
) VALUES (
  source.CUST_ID,
  source.EMAIL,
  source.TIER,
  source.EFFECTIVE_FROM,
  source.EFFECTIVE_TO,
  source.IS_CURRENT,
  source.SOURCE,
  source.RUN_ID,
  source.INGEST_SEQ
);